/**
 * The glyph key for a character: letters are drawn as capitals, '×' as the small x, and
 * anything the font doesn't have is a space (null).
 */
export function glyphKey(ch) {
  if (ch === '×') return 'x';
  const up = ch.toUpperCase();
  return Object.prototype.hasOwnProperty.call(FONT, up) ? up : null;
}

/** Width in pixels of a line of text in the 5 x 7 font. */
export function textWidth(text) {
  const n = String(text).length;
  return n === 0 ? 0 : n * FONT_ADVANCE - 1;
}

/** Width in pixels of a number in damage digits (outlined). */
export function digitsWidth(n) {
  const len = String(Math.max(0, Math.round(n))).length;
  return len * DIGIT_ADVANCE + 1;
}
